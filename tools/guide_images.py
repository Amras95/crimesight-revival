"""
Generates plugin/CrimeSightRevivalGuideImages.cs: the screenshots shown on some pages of the Revival Guide
(see GuideText.Image and CrimeSightRevivalGuide.cs). They go inside the code, in base64, so as not to have to
add resources to the .csproj.
  python tools/guide_images.py
Each image is made from one or more crops of a screenshot in the repo (one below the other), reduced to
WIDTH wide and saved as JPG.
"""
import base64
import io
import os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WIDTH, QUALITY, GAP = 1000, 82, 6
SESSION = "assets/screenshots/launcher_session.jpg"  # launcher with a session open
# name the plugin uses -> (repo screenshot, [crops (left, top, right, bottom)])
IMAGES = {
    "launcher": (SESSION, [(0, 141, 1259, 764)]),   # the four cards, the open session and the bottom bar
}
OUT = os.path.join(ROOT, "plugin", "CrimeSightRevivalGuideImages.cs")


def build(path, boxes):
    src = Image.open(os.path.join(ROOT, path)).convert("RGB")
    parts = [src.crop(b) for b in boxes]
    w = max(p.width for p in parts)
    h = sum(p.height for p in parts) + GAP * (len(parts) - 1)
    im = Image.new("RGB", (w, h), (12, 12, 20))
    y = 0
    for p in parts:
        im.paste(p, (0, y))
        y += p.height + GAP
    return im


def encode(im):
    if im.width > WIDTH:
        im = im.resize((WIDTH, round(im.height * WIDTH / im.width)), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, "JPEG", quality=QUALITY, optimize=True)
    return base64.b64encode(buf.getvalue()).decode("ascii"), im.size


def main():
    lines = [
        "// CRIMESIGHT Revival - Revival Guide screenshots. FILE GENERATED by tools/guide_images.py: don't edit it by hand.",
        "using System.Collections.Generic;",
        "",
        "namespace CrimeSightRevival.Mods",
        "{",
        "    static class GuideImages",
        "    {",
        "        /// <summary>Name -> JPG in base64.</summary>",
        "        public static readonly Dictionary<string, string> Data = new()",
        "        {",
    ]
    for name, (path, boxes) in IMAGES.items():
        b64, size = encode(build(path, boxes))
        lines.append(f"            // {path} ({size[0]}x{size[1]})")
        lines.append(f'            ["{name}"] =')
        chunks = [b64[i:i + 160] for i in range(0, len(b64), 160)]
        for i, c in enumerate(chunks):
            end = "," if i == len(chunks) - 1 else " +"
            lines.append(f'                "{c}"{end}')
    lines += ["        };", "    }", "}", ""]
    with open(OUT, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(lines))
    print("->", OUT)


if __name__ == "__main__":
    main()
