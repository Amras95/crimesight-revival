            }
            catch (Exception e) { Plugin.L.LogWarning("[Guia] pagina: " + e.Message); }
        }

        /// <summary>The topic's screenshot (if it has one) goes on top, and the text below; see Layout.</summary>
        static void SetPicture(Transform parent, int topic)
        {
            var name = GuideText.Image(topic);
            var tex = _pageNo > 0 ? null : topic == PadTopic ? ControllerTexture() : name == null ? null : PictureTexture(name);
            _laidOut = null;
            if (tex == null)
            {
                if (_pic != null) _pic.gameObject.SetActive(false);
                PadDiagram(topic);
                return;
            }
            if (_pic == null || _pic.transform.parent != parent)
            {
                var go = new GameObject("CSR_GuidePic");
                var rt = go.AddComponent<RectTransform>();
                rt.SetParent(parent, false);
                rt.anchorMin = rt.anchorMax = rt.pivot = new Vector2(0.5f, 1f);
                _pic = go.AddComponent<RawImage>();
                _pic.raycastTarget = false;
            }
            _pic.texture = tex;
            _pic.gameObject.SetActive(true);
            PadDiagram(topic);
        }

        /// <summary>Places the page: the screenshot on top, from side to side; the text below, always at BodySize
        /// (the
        /// pages with a screenshot have little text so it fits). Repeated if the page size changes (when
        /// opening it may not have it yet) or the text does.</summary>
        static void Layout()
        {
            if (_page == null || _shown == null) return;
            var size = _page.transform.parent.GetComponent<RectTransform>().rect.size;
            if (size.x <= 0 || size.y <= 0) return;
            bool pic = _pic != null && _pic.gameObject.activeSelf && _pic.texture != null;
            string key = size.x + "x" + size.y + (pic ? "p" : "") + _shown.Length;
            if (key == _laidOut) return;
            _laidOut = key;

            float w = size.x - 2 * Side, h = size.y + ExtraBelow - Top - Bottom;
            _page.enableAutoSizing = false;
            _page.fontSize = BodySize;
            float textH = _page.GetPreferredValues(_shown, w, 0).y;

            float picH = 0;
            if (pic)
            {
                float texAspect = _pic.texture.width / (float)Math.Max(1, _pic.texture.height);
                float aspect = _topic == PadTopic ? texAspect * PadDiagramWidth : texAspect;   // the gamepad has names on its sides
                float full = w / aspect;                                 // from side to side (the text goes in what is left)
                float left = h - textH - Gap;                            // what the text leaves free
                picH = full <= left ? full : Math.Min(full, Math.Max(left, h * PicMinShare));
                _pic.rectTransform.anchoredPosition = new Vector2(0, -Top);
                _pic.rectTransform.sizeDelta = new Vector2(Math.Min(w, picH * texAspect), picH);
                if (_topic == PadTopic) PadDiagramSize(picH);
            }
            var prt = _page.rectTransform;
            prt.anchorMin = Vector2.zero; prt.anchorMax = Vector2.one;
            prt.offsetMin = new Vector2(Side, Bottom - ExtraBelow);
            prt.offsetMax = new Vector2(-Side, -(Top + (pic ? picH + Gap : 0)));

            float room = h - (pic ? picH + Gap : 0);
            if (textH > room)                                            // it doesn't fit: only this page shrinks
            {
                _page.enableAutoSizing = true;
                _page.fontSizeMax = BodySize; _page.fontSizeMin = MinBodySize;
                Plugin.L.LogInfo($"[Guia] la pagina {_topic + 1} no cabe a {BodySize} ({textH:0} de {room:0} px): se reduce la letra");
            }
        }

        /// <summary>The screenshot (from GuideImages) as a texture; loaded once.</summary>
        static Texture2D PictureTexture(string name)
        {
            if (_picTex.TryGetValue(name, out var t)) return t;
            Texture2D tex = null;
            try
            {
                if (GuideImages.Data.TryGetValue(name, out var b64))
                {
                    tex = new Texture2D(2, 2, TextureFormat.RGBA32, false) { name = "csr_guide_" + name, hideFlags = HideFlags.DontUnloadUnusedAsset };
                    if (!ImageConversion.LoadImage(tex, Convert.FromBase64String(b64), false)) tex = null;
                }
                if (tex == null) Plugin.L.LogWarning("[Guia] no pude cargar la captura " + name);
            }
            catch (Exception e) { Plugin.L.LogWarning("[Guia] captura " + name + ": " + e.Message); tex = null; }
            _picTex[name] = tex;
            return tex;
        }

        /// <summary>Sets the topic's text (again if there are icons or stickers now that weren't there
        /// before).</summary>
        static void RefreshPage()
        {
            if (_page == null || _topic < 0) return;
            if (Pad.KeyIcons != null && _page.spriteAsset != Pad.KeyIcons) { _page.spriteAsset = Pad.KeyIcons; _shown = null; }
            var text = Icons(PageText());
            PadDiagram(_topic);                                          // the gamepad of the gamepad page (if the type changes)
            if (text == _shown) { Layout(); return; }
            _page.text = text;
            _shown = text;
            Layout();
        }

        // ------------------------------------------------------------ gamepad drawing ("Gamepad" page)
        // The gamepad page has a drawn gamepad on top (plugin/guide_controller.png, embedded in the DLL; see
        // tools/guide_controller.py). Over its buttons go the icons of the gamepad in use, and at the end of each
        // line what that button does (GuideText.PadLabels). Everything hangs from the image and scales with it.
        const int PadTopic = 2;
        const float PadLabelCol = 0.34f;                                   // width of each name column (in drawing widths)
        const float PadDiagramWidth = 1f + 2 * (PadLabelCol + 0.012f);   // total width (drawing + names) / drawing width
        const float PadImgW = 928f, PadCrop = 48f;                         // the drawing is cropped 48 px per side (from 1024)
        static Texture2D _padTex;
        static bool _padTexTried;
        static string _padKey;
        static readonly List<(TextMeshProUGUI t, float size)> _padIcons = new();   // size of the drawing in pixels (768 tall)
        static readonly List<TextMeshProUGUI> _padLabels = new();

        // button -> centre and size in the original template (1024x768; PadCrop is subtracted for the cropped
        // drawing)
        static readonly (string btn, float x, float y, float s)[] PadButtons =
        {
            ("lt", 290, 95, 58), ("rt", 730, 95, 58), ("lb", 272, 192, 46), ("rb", 752, 192, 46),
            ("back", 440, 325, 46), ("start", 572, 325, 46),
            ("y", 765, 290, 44), ("x", 700, 345, 44), ("b", 822, 347, 44), ("a", 765, 405, 44),
            ("lstick", 393, 458, 56), ("rstick", 632, 458, 56),
        };
        // height (in the drawing) of each line, in the order of GuideText.PadLabels: 8 on the left and 8 on the right
        static readonly float[] PadLines = { 58, 140, 240, 290, 342, 393, 445, 598 };

        static void PadDiagram(int topic)
        {
            try
            {
                string st = Pad.PadStyle ?? "xbox";
                string key = topic == PadTopic && _pic != null ? st + "|" + _lang + "|" + _pic.GetInstanceID() : null;
                if (key == _padKey) return;
                _padKey = key;
                foreach (var (t, _) in _padIcons) if (t != null) UnityEngine.Object.Destroy(t.gameObject);
                foreach (var t in _padLabels) if (t != null) UnityEngine.Object.Destroy(t.gameObject);
                _padIcons.Clear(); _padLabels.Clear();
                if (key == null) return;
                var font = _page != null ? _page.font : null;
                TextMeshProUGUI Make(string name, float x0, float y0, float x1, float y1)
                {
                    var go = new GameObject(name);
                    var rt = go.AddComponent<RectTransform>();
                    rt.SetParent(_pic.transform, false);
                    rt.anchorMin = new Vector2(x0, y0); rt.anchorMax = new Vector2(x1, y1);
                    rt.offsetMin = rt.offsetMax = Vector2.zero;
                    var t = go.AddComponent<TextMeshProUGUI>();
                    if (font != null) t.font = font;
                    t.enableWordWrapping = false;
                    t.raycastTarget = false;
                    return t;
                }
                foreach (var (btn, x, y, sz) in PadButtons)
                {
                    float h = sz / 768f, w = sz / PadImgW, cx = (x - PadCrop) / PadImgW;
                    var t = Make("CSR_PadIcon_" + btn, cx - w, 1 - y / 768f - h, cx + w, 1 - y / 768f + h);
                    if (Pad.KeyIcons != null) t.spriteAsset = Pad.KeyIcons;
                    string n = btn.EndsWith("stick") ? btn : st + "_" + btn;
                    t.text = $"<sprite name=\"csr_{n}\">";
                    t.alignment = TextAlignmentOptions.Center;
                    _padIcons.Add((t, sz));
                }
                var labels = GuideText.PadLabels(_lang);
                for (int i = 0; i < 16 && i < labels.Length; i++)
                {
                    bool left = i < 8;
                    float y = 1 - PadLines[i % 8] / 768f, half = 25f / 768f;
                    var t = left ? Make("CSR_PadLabel", -0.012f - PadLabelCol, y - half, -0.012f, y + half)
                                 : Make("CSR_PadLabel", 1.012f, y - half, 1.012f + PadLabelCol, y + half);
                    t.text = labels[i];
                    t.color = new Color32(40, 40, 40, 255);
                    t.alignment = left ? TextAlignmentOptions.MidlineRight : TextAlignmentOptions.MidlineLeft;
                    t.enableWordWrapping = true;                             // long ones wrap to two lines
                    t.lineSpacing = -18;
                    t.overflowMode = TextOverflowModes.Overflow;
                    _padLabels.Add(t);
                }
            }
            catch (Exception e) { Plugin.L.LogWarning("[Guia] dibujo del mando: " + e.Message); }
        }

        /// <summary>Font sizes of the gamepad drawing, depending on how tall it ended up.</summary>
        static void PadDiagramSize(float picH)
        {
            float k = picH / 768f;
            foreach (var (t, sz) in _padIcons) if (t != null) t.fontSize = sz * k * 0.95f;
            foreach (var t in _padLabels)
            {
                if (t == null) continue;
                t.enableAutoSizing = true;                               // the same for all, unless one doesn't fit
                t.fontSizeMax = Math.Max(10f, 36f * k);
                t.fontSizeMin = Math.Max(8f, 20f * k);
            }
        }

        static Texture2D ControllerTexture()
        {
            if (_padTex != null || _padTexTried) return _padTex;
            _padTexTried = true;
            try
            {
                using var st = typeof(Guide).Assembly.GetManifestResourceStream("CrimeSightRevival.GuideController.png");
                if (st == null) { Plugin.L.LogWarning("[Guia] falta el dibujo del mando en la DLL"); return null; }
                var ms = new System.IO.MemoryStream();
                st.CopyTo(ms);
                var tex = new Texture2D(2, 2, TextureFormat.RGBA32, false) { name = "csr_guide_controller", hideFlags = HideFlags.DontUnloadUnusedAsset };
                if (ImageConversion.LoadImage(tex, ms.ToArray(), false)) _padTex = tex;
            }
            catch (Exception e) { Plugin.L.LogWarning("[Guia] dibujo del mando: " + e.Message); }
            return _padTex;
        }

        // ------------------------------------------------------------ pages
        // A long topic is split into pages with {PAGE} (GuideText). The game's arrows (which in its tips go
        // with what the character says) here turn the guide's pages; the title has "page/total".
        // The screenshot (or the gamepad drawing) only shows on the first page.
        static string[] Pages() => (GuideText.Page(_topic, _lang) ?? "").Split(new[] { "{PAGE}" }, StringSplitOptions.None);

        static string PageText()
        {
            var p = Pages();
            _pageNo = Math.Max(0, Math.Min(_pageNo, p.Length - 1));
            return p[_pageNo].TrimStart('\r', '\n');
        }

        static bool BeforePrevPage() => !Active || !TurnPage(-1);
        static bool BeforeNextPage() => !Active || !TurnPage(1);

        static bool TurnPage(int dir)
        {
            try
            {
                if (_tips == null || _topic < 0) return false;
                int n = Pages().Length, to = Math.Max(0, Math.Min(n - 1, _pageNo + dir));
                if (to == _pageNo) return true;
                _pageNo = to;
                _shown = null;
                var img = _tips.tipsImage;
                if (img != null) SetPicture(img.transform, _topic);
                RefreshPage();
                return true;
            }
            catch (Exception e) { Plugin.L.LogWarning("[Guia] pagina: " + e.Message); return true; }
        }

        /// <summary>Every frame with the guide open: icons, stickers, text, page arrows and their number.</summary>
        static void GuideFrame()
        {
            if (!Active || _tips == null) return;
            if (Pad.KeyIcons == null) Pad.EnsureIcons();
            Stickers.Ensure();
            RefreshPage();
            int n = _topic >= 0 ? Pages().Length : 1;
            void Show(Button b, bool on) { if (b != null && b.gameObject.activeSelf != on) b.gameObject.SetActive(on); }
            Show(_tips.prevButton, n > 1 && _pageNo > 0);
            Show(_tips.nextButton, n > 1 && _pageNo < n - 1);
            var title = _tips.tipsTitleText;
            if (title != null && _topic >= 0)
            {
                string want = GuideText.TopicTitle(_topic, _lang) + $" {_pageNo + 1}/{n}";
                if (title.text != want) title.text = want;
            }
        }

        static readonly List<GameObject> _hidden = new();

        /// <summary>The "Start the tutorial" button has no place in the guide; it is given back before seeing a
        /// tutorial.</summary>
        static void HideTutorialStart(OutGameTips t, bool hide)
        {
            if (hide)
            {
                foreach (var go in new[] { t.tutorialNull, t.tutorialButton != null ? t.tutorialButton.gameObject : null })
                    if (go != null && go.activeSelf) { go.SetActive(false); _hidden.Add(go); }
                return;
            }
            foreach (var go in _hidden) try { if (go != null) go.SetActive(true); } catch { }
            _hidden.Clear();
        }

        static bool BeforeTutorialDisplay(OutGameTips __instance)
        {
            if (Active) return false;
            if (_hidden.Count > 0) HideTutorialStart(__instance, false);
            return true;
        }

        /// <summary>{A}, {LS}, {START}... -> icons of the gamepad in use (or the Xbox one if there is
        /// none).</summary>
        static string Icons(string text)
        {
            string st = Pad.PadStyle ?? "xbox";
            string S(string n) => $"<sprite name=\"csr_{n}\">";
            return text
                .Replace("{A}", S(st + "_a")).Replace("{B}", S(st + "_b")).Replace("{X}", S(st + "_x")).Replace("{Y}", S(st + "_y"))
                .Replace("{LBRB}", S(st + "_lbrb")).Replace("{LTRT}", S(st + "_ltrt"))
                .Replace("{LB}", S(st + "_lb")).Replace("{RB}", S(st + "_rb")).Replace("{LT}", S(st + "_lt")).Replace("{RT}", S(st + "_rt"))
                .Replace("{START}", S(st + "_start")).Replace("{BACK}", S(st + "_back"))
                .Replace("{LS}", S("lstick")).Replace("{RS}", S("rstick")).Replace("{DPAD}", S("dpad"))
                .Replace("{DUP}", S("dpad_up")).Replace("{DDOWN}", S("dpad_down")).Replace("{DLEFT}", S("dpad_left")).Replace("{DRIGHT}", S("dpad_right"))
                .Replace("{ST_IRENE}", Stickers.Tag(38)).Replace("{ST_SUS}", Stickers.Tag(25)).Replace("{ST_NOSUS}", Stickers.Tag(24))
                .Replace("{H}", "<color=#1f6e57>").Replace("{/H}", "</color>");
        }
    }

    /// <summary>The game's sticker images, to put them inside the guide's text.</summary>
    static class Stickers
    {
        static readonly Dictionary<int, string> _names = new();   // sticker type -> icon name
        static readonly HashSet<int> _wanted = new() { 38, 25, 24 };   // Irene "killer", I suspect, I don't think
        // 24 and 25 have one version per character (killerSuspicion_I, _M, _S, _W...): the guide uses them on
        // Watson's page
        static readonly Dictionary<int, string> _suffix = new() { [24] = "_W", [25] = "_W" };
        static float _nextTry;

        /// <summary>The sticker's icon for TextMeshPro, or nothing if it isn't there yet.</summary>
        public static string Tag(int type) => _names.TryGetValue(type, out var n) ? $"<sprite name=\"{n}\">" : "";

        public static void Ensure()
        {
            if (_names.Count >= _wanted.Count || Time.unscaledTime < _nextTry) return;
            _nextTry = Time.unscaledTime + 2f;
            var root = Pad.KeyIcons;
            if (root == null) return;
            try
            {
                foreach (var o in Resources.FindObjectsOfTypeAll(Il2CppType.Of<StampData>()))
                {
                    var d = o == null ? null : o.TryCast<StampData>();
                    if (d == null) continue;
                    int type;
                    try { type = (int)d.GetStampType(); } catch { continue; }
                    if (!_wanted.Contains(type) || _names.ContainsKey(type)) continue;
                    var sp = d.spriteImageThumbnail ?? d.spriteImage;
                    if (sp == null || sp.texture == null) continue;
                    if (_suffix.TryGetValue(type, out var suf) && !sp.name.EndsWith(suf)) continue;
                    var name = "csr_stamp_" + type;
                    var asset = Build(root, sp, name);
                    if (asset == null) continue;
                    if (root.fallbackSpriteAssets == null) root.fallbackSpriteAssets = new Il2CppSystem.Collections.Generic.List<TMP_SpriteAsset>();
                    root.fallbackSpriteAssets.Add(asset);
                    _names[type] = name;
                    Plugin.L.LogInfo($"[Guia] sticker {type} listo ({sp.name})");
                }
            }
            catch (Exception e) { Plugin.L.LogWarning("[Guia] stickers: " + e.Message); _nextTry = float.MaxValue; }
        }

        /// <summary>A game sprite as a TextMeshPro icon (without copying the image: its texture is used as it
        /// is).</summary>
        static TMP_SpriteAsset Build(TMP_SpriteAsset root, Sprite sp, string name)
        {
            int refIdx = root.GetSpriteIndexFromName("keyboard_ctrl");
            if (refIdx < 0 || root.spriteCharacterTable.Count == 0) refIdx = 0;
            var refChar = root.spriteCharacterTable[refIdx];
            var refGlyph = root.spriteGlyphTable[(int)Math.Min(refChar.glyphIndex, (uint)(root.spriteGlyphTable.Count - 1))];
            var rm = refGlyph.metrics;

            var a = UnityEngine.Object.Instantiate(root);
            a.name = name;
            a.hideFlags = HideFlags.DontUnloadUnusedAsset;
            var tex = sp.texture;
            a.spriteSheet = tex;
            var mat = new Material(root.material) { name = name + "_mat", hideFlags = HideFlags.DontUnloadUnusedAsset };
            mat.mainTexture = tex;
            a.material = mat;
            a.hashCode = TMP_TextUtilities.GetSimpleHashCode(a.name);
            a.materialHashCode = TMP_TextUtilities.GetSimpleHashCode(mat.name);

            var r = sp.textureRect;
            float h = rm.height * 2.2f;                                  // a bit bigger than a line
            float w = h * (r.width / Math.Max(1f, r.height));
            var metrics = new UnityEngine.TextCore.GlyphMetrics(w, h, 0, rm.horizontalBearingY + (h - rm.height) * 0.6f, w + rm.height * 0.2f);
            var g = new TMP_SpriteGlyph(0, metrics,
                new UnityEngine.TextCore.GlyphRect((int)r.x, (int)r.y, (int)r.width, (int)r.height), refGlyph.scale, 0);
            a.spriteGlyphTable.Clear();
            a.spriteCharacterTable.Clear();
            a.spriteGlyphTable.Add(g);
            a.spriteCharacterTable.Add(new TMP_SpriteCharacter(0xFFFE, g) { name = name });
            a.fallbackSpriteAssets = new Il2CppSystem.Collections.Generic.List<TMP_SpriteAsset>();
            a.UpdateLookupTables();
            return a;
        }
    }
