// CRIMESIGHT Revival - "Revival Guide": how what Revival adds works, inside the game.
//
// The "Play" menu has a third small button, "Tips", which the game leaves switched off next to "Tutorial".
// Here it is switched on with the name "Revival Guide" and opens the game's tips screen (the same one as
// Tutorial and Training: list on the left, title, pages with arrows). While it is opened from
// that button, the list only has the guide's entries (registered as game tips) and each page's text,
// with the icons of the gamepad buttons you use, goes where the image normally goes.
// The guide's texts are in GuideText.cs (one version per game language, all 11).
// All pages use the same font size (BodySize). The ones with a screenshot (GuideText.Image) show
// it at the top, from side to side, and the text below; the screenshots are in GuideImages.cs, generated by
